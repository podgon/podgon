create table categories (
    id         uuid primary key,
    key        varchar(60) not null,
    parent_id  uuid references categories (id),
    -- заготовка под категории групп (вариант К-Б): null — общий набор
    group_id   uuid references groups (id) on delete cascade,
    sort_order int         not null,
    -- «Без категории» (key = none): только для личных рекомендаций
    system     boolean     not null default false,
    archived   boolean     not null default false,
    constraint categories_key_uq unique (key),
    constraint categories_not_self_parent check (parent_id is distinct from id)
);
create index categories_parent_idx on categories (parent_id);

create table category_names (
    category_id uuid         not null references categories (id) on delete cascade,
    locale      varchar(8)   not null,
    name        varchar(100) not null,
    primary key (category_id, locale)
);


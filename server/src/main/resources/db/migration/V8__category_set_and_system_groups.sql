-- Этап 8.2.1 (редизайн, ADR-011): общий набор категорий вместо категорий групп, категория — на рекомендации,
-- системные группы «Личное» и «Избранное». Данные в БД тестовые (docs/design.md, Л4).

-- 1. Набор категорий (docs/categories.md). UUID категории получается из стабильного ключа, поэтому одинаков
-- во всех базах; ключ не меняется и не переиспользуется, категорию не удаляют, а скрывают (archived).
create function category_uuid(key text) returns uuid as
$$
select md5('podgon:category:' || key)::uuid
$$ language sql immutable;

alter table review_groups drop constraint review_groups_category_fk;

-- старая категория публикации → ключ набора (по шаблону V4); не нашлось — «Без категории»
create temporary table legacy_review_category on commit drop as
select distinct on (g.review_id) g.review_id,
       case c.template_id
           when '00000000-0000-4000-8000-000000000001' then 'books'
           when '00000000-0000-4000-8000-000000000002' then 'film'
           when '00000000-0000-4000-8000-000000000003' then 'music'
           when '00000000-0000-4000-8000-000000000004' then 'food'
           when '00000000-0000-4000-8000-000000000005' then 'travel'
           when '00000000-0000-4000-8000-000000000006' then 'travel.places'
           when '00000000-0000-4000-8000-000000000007' then 'travel.hotels'
           when '00000000-0000-4000-8000-000000000008' then 'services'
           when '00000000-0000-4000-8000-000000000009' then 'shopping'
           when '00000000-0000-4000-8000-000000000010' then 'games'
           end as key
from review_groups g
         join categories c on c.id = g.category_id
order by g.review_id, (c.template_id is null), g.shared_at;

alter table review_groups drop column category_id;
drop table categories;
drop table category_template_translations;

alter table reviews alter column category_id set not null;
create index reviews_category_idx on reviews (category_id);

-- 2. Системные группы: тип группы и владелец (created_by). Участников и ролей у них нет — поэтому они
-- не попадают в списки групп, лимит групп, ленту «Все» и управление группой.
alter table groups
    add column kind varchar(16) not null default 'REGULAR',
    add constraint groups_kind_check check (kind in ('REGULAR', 'PERSONAL', 'FAVORITES'));
create unique index groups_system_owner_uq on groups (created_by, kind) where kind <> 'REGULAR';

insert into groups (id, name, description, created_by, created_at, updated_at, kind)
select gen_random_uuid(), '', '', u.id, now(), now(), k.kind
from users u
         cross join (values ('PERSONAL'), ('FAVORITES')) as k (kind)
where u.deleted_at is null and u.status in ('ACTIVE', 'BLOCKED');

-- рекомендации без публикаций становятся личными (Л4); у служебного «удалённого пользователя» их никто не видит
insert into review_groups (review_id, group_id, shared_at)
select r.id, g.id, r.created_at
from reviews r
         join groups g on g.created_by = r.author_id and g.kind = 'PERSONAL'
where not exists (select 1 from review_groups x where x.review_id = r.id);
delete from reviews r where not exists (select 1 from review_groups x where x.review_id = r.id);

-- 3. Теги: «ё» = «е» (как в поиске, V7). Совпавшие после замены теги сливаются.
insert into tags (name)
select distinct translate(name, 'ёЁ', 'еЕ') from tags where name ~ '[ёЁ]'
on conflict (name) do nothing;
insert into review_tags (review_id, tag_id)
select rt.review_id, n.id
from review_tags rt
         join tags t on t.id = rt.tag_id
         join tags n on n.name = translate(t.name, 'ёЁ', 'еЕ')::citext
where t.name ~ '[ёЁ]'
on conflict do nothing;
delete from review_tags where tag_id in (select id from tags where name ~ '[ёЁ]');
delete from tags where name ~ '[ёЁ]';

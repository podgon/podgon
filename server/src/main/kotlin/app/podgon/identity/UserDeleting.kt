package app.podgon.identity

import java.util.UUID

/** Идентификатор служебного пользователя «Удалённый пользователь» (создаётся миграцией V2). */
val DELETED_USER_ID: UUID = UUID.fromString("00000000-0000-0000-0000-000000000001")

/**
 * Событие модуля identity: аккаунт сейчас будет удалён. Публикуется синхронно в транзакции удаления;
 * обработчики (группы, рекомендации) снимают с пользователя связи, а исключение откатывает удаление.
 */
data class UserDeleting(
    val userId: UUID,
    /** Удалить все рекомендации пользователя; иначе опубликованные переходят «удалённому пользователю». */
    val deleteReviews: Boolean,
)
